// Builds the word finder's dictionary from SCOWL (npm package wordlist-english). Its copyright and permission
// notice ships with the site at public/licenses/scowl.txt and is linked from the word finder page.
// English and American lists up to size 60: common words, not the obscure ones. Plain a to z words of 3 to 7 letters.
// Writes src/lib/generated/words.ts (gitignored), which only the word finder page loads. Runs before dev and build.

import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, "..");

const SIZES = [10, 20, 35, 40, 50, 55, 60];
const DIALECTS = ["english", "american"];

const words = new Set();
for (const dialect of DIALECTS) {
  for (const size of SIZES) {
    for (const word of require(`wordlist-english/${dialect}-words-${size}.json`)) {
      if (/^[a-z]{3,7}$/.test(word)) words.add(word);
    }
  }
}

const sorted = [...words].sort();
const out = path.join(root, "src/lib/generated/words.ts");
await mkdir(path.dirname(out), { recursive: true });
await writeFile(
  out,
  `// Generated by scripts/words.mjs. Do not edit.\n// Word list from SCOWL, Copyright 2000-2016 by Kevin Atkinson. Notice and permission: /licenses/scowl.txt\nconst WORDS = ${JSON.stringify(sorted.join("\n"))};\nexport default WORDS;\n`,
);
console.log(`words: ${sorted.length} words of 3 to 7 letters`);
